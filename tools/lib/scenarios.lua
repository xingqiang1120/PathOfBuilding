-- Path of Building
--
-- Scenarios: the same build under different fights. A build's Config holds its author's assumptions, which are
-- usually right for the content the author plays (e.g. 50 corpses consumed recently while mapping through dense
-- packs) but not for others (a single boss leaves no corpses). Each rule says, for one Config key, what the
-- assumption depends on and what value a scenario implies, with the reason, so the numbers can be explained.
--
-- Scenarios
--   asSaved  the build's own Config (the author's assumptions)
--   mapping  as saved, against normal monsters (no boss modifiers): the author's density assumptions are kept
--   boss     one pinnacle boss, no other monsters: density assumptions are replaced by what the build supplies itself
--
-- Kinds
--   density    depends on many monsters (corpses, kills, nearby enemies): kept for mapping, re-estimated for a boss
--   fightPhase true only for part of a fight (enemy on low life): blended by the share of the fight
--   sustained  generated by the build (charges, rage, warcry, buffs): kept if the build has a source, flagged if not
--   fight      the enemy itself (boss modifiers)

local M = { }

M.LOW_LIFE_SHARE = 0.35 -- an enemy is on low life at or below 35% of its life (PoE Wiki, "Low life")
M.RECENT = 4            -- "recently" = the past 4 seconds (PoE Wiki, "Recently")

local function lines(ctx, ...)
	local found = { }
	for _, pattern in ipairs({ ... }) do
		for _, line in ipairs(ctx.lines) do
			if line.text:lower():find(pattern) then
				table.insert(found, line.source .. ": " .. line.text)
			end
		end
	end
	return found
end

-- How a source line is triggered, from its wording
local triggers = {
	{ "kill", { "on kill", "when you kill", "killed recently", "on killing" } },
	{ "beingHit", { "when you are hit", "been hit recently", "when hit", "when you take" } },
	{ "block", { "when you block", "on block" } },
	{ "hit", { "on hit", "on melee hit", "on attack hit", "when you hit", "on critical strike", "on melee critical strike", "when you crit", "on hitting" } },
	{ "cast", { "when you cast", "when you use", "on use" } },
	{ "time", { "every second", "per second", "every %d+ seconds" } },
}

local function triggerOf(text)
	for _, t in ipairs(triggers) do
		for _, pattern in ipairs(t[2]) do
			if text:find(pattern) then return t[1] end
		end
	end
	return "other"
end

-- Lines that generate a resource (not "+1 to maximum", "per charge", "while you have")
local function generators(ctx, resource, extra)
	local found = { }
	for _, line in ipairs(ctx.lines) do
		local t = line.text:lower()
		local generates = t:find(resource, 1, true) and (t:find("^gain") or t:find("chance to gain") or t:find("grants? ") or t:find(" gain ")
			or (extra and t:find(extra))) and not t:find("maximum") and not t:find("per " .. resource, 1, true) and not t:find("while you have")
		if generates then
			table.insert(found, { text = line.source .. ": " .. line.text, trigger = triggerOf(t), line = t })
		end
	end
	return found
end

-- A resource the build has to generate itself: kept when it has a source, off for a boss when every source needs kills
local function sustained(ctx, saved, label, resource, skills, extra)
	local found = generators(ctx, resource, extra)
	for _, name in ipairs(skills or { }) do
		if ctx.hasSkill(name) then
			table.insert(found, { text = "skill: " .. name, trigger = "skill" })
		end
	end
	if #found == 0 then
		return saved, saved, string.format("%s: no source found in the build's items, passives or skills - probably only a Config setting", label), nil, true
	end
	local texts, onlyKills = { }, true
	for _, f in ipairs(found) do
		table.insert(texts, f.text .. " [" .. f.trigger .. "]")
		if f.trigger ~= "kill" then onlyKills = false end
	end
	if onlyKills then
		local off = type(saved) == "number" and 0 or false
		return saved, off, string.format("%s: only gained on kill (%s) - kept while mapping, none against a boss alone", label, found[1].text), texts
	end
	return saved, saved, string.format("%s: the build generates it (%s)", label, found[1].text), texts
end

-- Uptime of a buff gained by chance on hit/crit for a duration: 1 - (1 - p)^(triggers in one duration)
function M.chanceUptime(chance, duration, perSecond)
	return 1 - (1 - chance / 100) ^ (perSecond * duration)
end

-- Corpses the build makes and uses itself, per "recently" (4 s)
local function corpseSupply(ctx)
	local created, consumers = 0, nil
	local notes = { }
	local rate = ctx.rate("Desecrate")
	if rate and rate > 0 then
		created = created + rate * 5 * M.RECENT -- desecrate_number_of_corpses_to_create
		table.insert(notes, string.format("Desecrate %.2f/s x 5 corpses", rate))
	end
	local consume = 0
	for _, c in ipairs({ { "Volatile Dead", 10 }, { "Volatile Dead of Seething", 10 }, { "Volatile Dead of Confinement", 10 },
		{ "Bone Offering", 1 }, { "Flesh Offering", 1 }, { "Spirit Offering", 1 }, { "Detonate Dead", 1 }, { "Unearth", 1 } }) do
		local r = ctx.rate(c[1])
		if r and r > 0 then
			consume = consume + r * c[2] * M.RECENT
			consumers = true
			table.insert(notes, string.format("%s %.2f/s x %d", c[1], r, c[2]))
		end
	end
	return created, consumers and consume or nil, notes
end

M.rules = {
	{ key = "enemyIsBoss", kind = "fight", label = "Enemy is a boss",
		mapping = function(ctx, saved) return "None", "normal monsters: no boss resistances or damage reduction" end,
		boss = function(ctx, saved)
			if saved == "Uber" then return saved, "uber pinnacle boss as saved" end
			return "Pinnacle", "pinnacle boss: higher resistances, less damage taken from ailments and curses"
		end },
	{ key = "conditionEnemyLowLife", kind = "fightPhase", label = "Enemy is on Low Life",
		share = function() return M.LOW_LIFE_SHARE, "an enemy is on low life for its last 35% of life: with steady damage about 35% of the fight" end },
	{ key = "multiplierNearbyEnemies", kind = "density", label = "Nearby enemies",
		boss = function(ctx, saved) return math.min(saved, 1), "a boss alone" end },
	{ key = "conditionKilledRecently", kind = "density", label = "Killed recently",
		boss = function(ctx, saved) return false, "no kills while only the boss is there" end },
	{ key = "conditionSpawnedCorpseRecently", kind = "density", label = "Spawned a corpse recently",
		boss = function(ctx, saved)
			local created = corpseSupply(ctx)
			return created >= 1, created >= 1 and "the build creates corpses itself (Desecrate)" or "no corpse creation in the build"
		end },
	{ key = "conditionConsumedCorpseRecently", kind = "density", label = "Consumed a corpse recently",
		boss = function(ctx, saved)
			local created, consume = corpseSupply(ctx)
			local ok = created >= 1 and (consume == nil or consume >= 1)
			return ok, ok and "the build creates and consumes its own corpses" or "no corpses on a boss unless the build makes them"
		end },
	{ key = "multiplierCorpseConsumedRecently", kind = "density", label = "Corpses consumed recently",
		boss = function(ctx, saved)
			local created, consume, notes = corpseSupply(ctx)
			local value = math.min(saved, math.floor(created), consume and math.floor(consume) or math.huge)
			return value, string.format("corpses the build makes in 4 s: %d%s%s", math.floor(created),
				consume and string.format(", can consume %d", math.floor(consume)) or "", #notes > 0 and (" (" .. table.concat(notes, "; ") .. ")") or "")
		end },
	{ key = "multiplierNearbyCorpse", kind = "density", label = "Nearby corpses",
		boss = function(ctx, saved)
			local created = corpseSupply(ctx)
			local value = created >= 1 and math.min(saved, 10) or 0 -- desecrate_maximum_number_of_corpses
			return value, created >= 1 and "Desecrate keeps up to 10 corpses" or "no corpses on a boss unless the build makes them"
		end },
	{ key = "multiplierRage", kind = "sustained", label = "Rage",
		check = function(ctx, saved) return sustained(ctx, saved, "Rage", "rage", { "Rage", "Berserk" }) end },
	{ key = "configUnholyResonanceCount", kind = "sustained", label = "Unholy Resonance (lowest)",
		check = function(ctx, saved)
			if ctx.hasSkill("Unholy Trinity") then
				return saved, saved, "Unholy Trinity grants resonance on hit (2 s each, max 50 per type); the lowest type depends on the damage mix, so the value needs checking in play", { "Unholy Trinity" }
			end
			return saved, saved, "no Unholy Trinity in the build", nil, true
		end },
	{ key = "conditionUsedWarcryRecently", kind = "sustained", label = "Used a warcry recently",
		check = function(ctx, saved) return sustained(ctx, saved, "Warcry", "warcry", { "General's Cry", "Ancestral Cry", "Battlemage's Cry",
			"Enduring Cry", "Infernal Cry", "Intimidating Cry", "Rallying Cry", "Seismic Cry" }) end },
	{ key = "buffUnholyMight", kind = "sustained", label = "Unholy Might",
		check = function(ctx, saved)
			local mapping, boss, reason, sources, missing = sustained(ctx, saved, "Unholy Might", "unholy might")
			-- "X% chance to gain Unholy Might for N seconds on Critical Strike / Hit": estimate the uptime
			for _, line in ipairs(ctx.lines) do
				local t = line.text:lower()
				local chance, duration, on = t:match("(%d+)%% chance to gain unholy might for (%d+) seconds on (%a+)")
				if chance and ctx.hitsPerSecond then
					local perSecond = on == "critical" and ctx.critsPerSecond or ctx.hitsPerSecond
					local uptime = M.chanceUptime(tonumber(chance), tonumber(duration), perSecond)
					return mapping, boss, string.format("%s: %s%% chance for %s s on %s, %.1f per second -> about %.0f%% uptime", line.source, chance, duration,
						on == "critical" and "critical strike" or "hit", perSecond, uptime * 100), sources, missing, uptime < 0.95 and uptime or nil
				end
			end
			return mapping, boss, reason, sources, missing
		end },
	{ key = "usePowerCharges", kind = "sustained", label = "Power charges",
		check = function(ctx, saved) return sustained(ctx, saved, "Power charges", "power charge", { "Power Charge On Critical", "Assassin's Mark" }) end },
	{ key = "useFrenzyCharges", kind = "sustained", label = "Frenzy charges",
		check = function(ctx, saved) return sustained(ctx, saved, "Frenzy charges", "frenzy charge", { "Frenzy" }) end },
	{ key = "useEnduranceCharges", kind = "sustained", label = "Endurance charges",
		check = function(ctx, saved) return sustained(ctx, saved, "Endurance charges", "endurance charge", { "Enduring Cry" }) end },
	{ key = "buffFortification", kind = "sustained", label = "Fortification",
		check = function(ctx, saved) return sustained(ctx, saved, "Fortify", "fortif", { "Fortify" }, "fortify for") end },
}

return M
